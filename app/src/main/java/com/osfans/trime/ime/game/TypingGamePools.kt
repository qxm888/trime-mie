    /** 内置常用字（去重、过滤非 CJK）。 */
    val builtinChars: List<String> by lazy {
        FREQ.mapNotNull { c ->
            val v = c.code
            if (v in 0x3400..0x4DBF || v in 0x4E00..0x9FFF || v in 0xF900..0xFAFF) c.toString() else null
        }.distinct()
    }

    data class Pools(val chars: List<String>, val words: List<String>, val sentences: List<String>)

    /** 关卡字池：1-10 前500，11-20 前1000，21-30 前2000，31-40 前3000；41+ 加词组，46+ 加句子。外部字库无中文时回退内置。 */
    fun forLevel(level: Int, external: Pools?): Pools {
        val useExternal = external != null && (external.chars.isNotEmpty() || external.words.isNotEmpty() || external.sentences.isNotEmpty())
        val chars = external?.chars?.takeIf { it.isNotEmpty() } ?: builtinChars
        val limit = when {
            level <= 10 -> minOf(500, chars.size)
            level <= 20 -> minOf(1000, chars.size)
            level <= 30 -> minOf(2000, chars.size)
            else -> chars.size
        }
        val charPool = chars.take(limit)
        val words = external?.words?.takeIf { it.isNotEmpty() } ?: BUILTIN_WORDS
        val sentences = external?.sentences?.takeIf { it.isNotEmpty() } ?: BUILTIN_SENTENCES
        val withWords = level >= 41
        val withSentences = level >= 46
        return Pools(
            chars = charPool,
            words = if (withWords) words else emptyList(),
            sentences = if (withSentences) sentences else emptyList(),
        )
    }

    /** 外部 txt 字库：唯一 CJK 字按出现次数降序；2-4 字行为词组，5-14 字行为句子。 */
    fun parseExternal(text: String): Pools {
        val counts = linkedMapOf<String, Int>()
        val words = linkedSetOf<String>()
        val sentences = linkedSetOf<String>()
        text.lineSequence().forEach { raw ->
            val line = raw.trim()
            if (line.isEmpty()) return@forEach
            val cjk = line.count { ch -> val v = ch.code; v in 0x3400..0x4DBF || v in 0x4E00..0x9FFF || v in 0xF900..0xFAFF }
            when {
                line.length in 2..4 && cjk == line.length -> words.add(line)
                line.length in 5..14 && cjk >= line.length - 2 -> sentences.add(line)
            }
            line.forEach { ch ->
                val v = ch.code
                if (v in 0x3400..0x4DBF || v in 0x4E00..0x9FFF || v in 0xF900..0xFAFF) {
                    counts[ch.toString()] = (counts[ch.toString()] ?: 0) + 1
                }
            }
        }
        return Pools(chars = counts.entries.sortedByDescending { it.value }.map { it.key }, words = words.toList(), sentences = sentences.toList())
    }

    fun fromFile(file: File): Pools =
        parseExternal(file.readText(Charsets.UTF_8).let { if (it.length > 4 * 1024 * 1024) it.take(4 * 1024 * 1024) else it })
}
