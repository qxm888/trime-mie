#!/usr/bin/env python3
"""Read body vector colors for mini standing limbs; catalog accents may be a different color."""
from pathlib import Path
import re
import xml.etree.ElementTree as ET
ROOT=Path(__file__).resolve().parents[1]
SRC=ROOT/'app/src/main/java/com/osfans/trime/ui/pets'
NS='{http://schemas.android.com/apk/res/android}'
entries=[]
for id,resource in re.findall(r'"([^"\n]+)" -> R\.drawable\.(\w+)',(SRC/'PetArtwork.kt').read_text().split('fun body(id:String)=when(id) {',1)[1]):
    first=ET.parse(ROOT/f'app/src/main/res/drawable/{resource}.xml').getroot().find('path')
    if first is None: continue
    colors=[v.get(NS+'color') for v in first.iter('item')]
    if colors:
        if len(colors)%2: color=colors[len(colors)//2]
        else:
            a,b=[int(c[-6:],16) for c in (colors[0],colors[-1])]
            color='#'+''.join(f'{(((a>>s)&255)+((b>>s)&255))//2:02x}' for s in [16,8,0])
    else: color=first.get(NS+'fillColor')
    if not color or not re.fullmatch(r'#[0-9a-fA-F]{6}',color): continue
    entries.append(f'        "{id}" -> 0xff{color[1:].lower()}.toInt()')
(SRC/'PetMiniPalette.kt').write_text('''/* SPDX-License-Identifier: GPL-3.0-or-later */
// Generated by tools/generate_pet_standing_palette.py from the body artwork, not UI accents.
package com.osfans.trime.ui.pets

internal object PetMiniPalette {
    fun body(id:String,fallback:Int):Int=when(id) {
'''+ '\n'.join(entries)+'''
        else -> fallback
    }
}
''')
